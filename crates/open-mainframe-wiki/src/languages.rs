fn rexx_reference() -> String {
    r#"# REXX Language Reference

[Back to Languages](../index.md)

## Overview

REXX (Restructured Extended Executor) is an interpreted scripting language where
**every value is a string**. Numbers are strings that happen to look numeric.
Arithmetic is performed on string representations with arbitrary precision.

## Value Model

- All values are character strings
- Numbers are strings matching a numeric pattern (optional sign, digits, optional decimal, optional exponent)
- Arithmetic precision controlled by `NUMERIC DIGITS` (default 9)
- Comparison: strict (`==`, `\==`, `>>`, `<<`) vs. normal (`=`, `\=`, `>`, `<`)

## Control Flow

### DO/END
```rexx
DO i = 1 TO 10 BY 2        /* counted */
DO WHILE condition          /* pre-test */
DO UNTIL condition          /* post-test */
DO FOREVER                  /* infinite */
DO 5                        /* simple repeat */
```

### IF/THEN/ELSE
```rexx
IF condition THEN
  instruction
ELSE
  instruction
```

### SELECT/WHEN/OTHERWISE
```rexx
SELECT
  WHEN cond1 THEN instr1
  WHEN cond2 THEN instr2
  OTHERWISE instrn
END
```

### Loop Control
- `ITERATE` - skip to next iteration (like `continue`)
- `LEAVE` - exit loop (like `break`)
- `ITERATE name` / `LEAVE name` - target a named DO loop

## PARSE Instruction

| Variant | Source |
|---------|--------|
| `PARSE ARG` | Argument string |
| `PARSE PULL` | Data stack or terminal (uppercase) |
| `PARSE VAR name` | Named variable |
| `PARSE VALUE expr WITH` | Expression result |
| `PARSE SOURCE` | Program invocation info |
| `PARSE VERSION` | Interpreter version |
| `PARSE NUMERIC` | Current NUMERIC settings |
| `PARSE LINEIN` | Terminal input (no stack) |

Template patterns: literal delimiters, positional (absolute `=n`, relative `+n`/`-n`), variable.

## Builtin Functions (70+)

### String Functions
`ABBREV`, `CENTER`/`CENTRE`, `CHANGESTR`, `COMPARE`, `COPIES`, `COUNTSTR`,
`DELSTR`, `INSERT`, `LASTPOS`, `LEFT`, `LENGTH`, `OVERLAY`, `POS`,
`REVERSE`, `RIGHT`, `SPACE`, `STRIP`, `SUBSTR`, `SUBWORD`, `TRANSLATE`,
`VERIFY`, `WORDINDEX`, `WORDLENGTH`, `WORDPOS`, `WORDS`

### Word Functions
`DELWORD`, `SUBWORD`, `WORD`, `WORDINDEX`, `WORDLENGTH`, `WORDPOS`, `WORDS`

### Numeric Functions
`ABS`, `FORMAT`, `MAX`, `MIN`, `RANDOM`, `SIGN`, `TRUNC`

### Conversion Functions
`B2X`, `C2D`, `C2X`, `D2C`, `D2X`, `X2B`, `X2C`, `X2D`

### Bit/Logical Functions
`BITAND`, `BITOR`, `BITXOR`

### I/O Functions
`CHARIN`, `CHAROUT`, `CHARS`, `LINEIN`, `LINEOUT`, `LINES`, `STREAM`

### Comparison/Information
`DATATYPE`, `DIGITS`, `FORM`, `FUZZ`, `QUEUED`, `SOURCELINE`, `SYMBOL`,
`TRACE`, `VALUE`, `ADDRESS`, `ARG`, `CONDITION`, `DATE`, `ERRORTEXT`, `TIME`

## Stem Variables and Compound Variables

```rexx
stem.        = ''      /* set default value */
stem.1       = 'first'
stem.2       = 'second'
stem.0       = 2       /* conventional count */
stem.key     = 'value' /* associative array */
stem.i.j     = 'grid'  /* multi-dimensional */
```

Tail components are uppercased and concatenated with dots. The value of `stem.expr`
uses the current value of `expr` as the tail.

## Host Command Environments

| Environment | Purpose | Example |
|-------------|---------|---------|
| `TSO` | TSO commands (default in TSO) | `ADDRESS TSO "ALLOC FI(IN) DA('MY.DATA') SHR"` |
| `MVS` | MVS system commands | `ADDRESS MVS "EXECIO * DISKR mydd (STEM line. FINIS"` |
| `ISPEXEC` | ISPF dialog services | `ADDRESS ISPEXEC "DISPLAY PANEL(MYPANEL)"` |
| `ISREDIT` | ISPF editor macros | `ADDRESS ISREDIT "(LINE) = LINE .ZCSR"` |
| `CONSOLE` | MVS console commands | `ADDRESS CONSOLE "D A,L"` |
| `LINK` / `LINKMVS` | Call load modules | `ADDRESS LINKMVS "MYPROG parms"` |

## SIGNAL ON (Exception Handling)

| Condition | Triggered By |
|-----------|-------------|
| `ERROR` | Host command returns non-zero RC |
| `FAILURE` | Host command fails completely |
| `HALT` | External interrupt |
| `NOVALUE` | Uninitialized variable referenced |
| `SYNTAX` | Syntax or runtime error |
| `NOTREADY` | I/O not ready |

```rexx
SIGNAL ON NOVALUE NAME trap_novalue
SIGNAL ON SYNTAX NAME trap_syntax
```

Special variables set on trap: `SIGL` (line number), `RC` (return code).
`CONDITION('C')` returns condition name, `CONDITION('D')` returns description.

## Numeric Settings

```rexx
NUMERIC DIGITS 15      /* precision (default 9) */
NUMERIC FUZZ 2          /* digits ignored in comparison */
NUMERIC FORM SCIENTIFIC /* exponential notation (default) */
NUMERIC FORM ENGINEERING
```

---
*Generated by Mainframe Code Wiki*
"#.to_string()
}

