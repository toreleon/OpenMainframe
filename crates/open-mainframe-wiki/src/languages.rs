//! Language reference page generators for all 9 mainframe languages.

use std::fs;

use crate::{WikiConfig, WikiResult};

/// Generate all language reference pages.
pub fn generate_language_pages(config: &WikiConfig) -> WikiResult<()> {
    let out = &config.output_dir;
    fs::write(out.join("languages/index.md"), languages_index())?;
    fs::write(out.join("languages/cobol/index.md"), cobol_reference())?;
    fs::write(out.join("languages/jcl/index.md"), jcl_reference())?;
    fs::write(out.join("languages/rexx/index.md"), rexx_reference())?;
    fs::write(out.join("languages/hlasm/index.md"), hlasm_reference())?;
    fs::write(out.join("languages/pli/index.md"), pli_reference())?;
    fs::write(out.join("languages/clist/index.md"), clist_reference())?;
    fs::write(out.join("languages/easytrieve/index.md"), easytrieve_reference())?;
    fs::write(out.join("languages/natural/index.md"), natural_reference())?;
    fs::write(out.join("languages/focus/index.md"), focus_reference())?;
    Ok(())
}

